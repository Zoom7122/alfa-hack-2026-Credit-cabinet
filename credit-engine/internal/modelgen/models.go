type ModelsOutput struct{ Artifacts []Artifact }

// GenerateModels emits Go composites, typed facts bindings and the catalog.
// No JSON definition is parsed during working evaluation.
func GenerateModels(definitions []model.ModelDefinition) (ModelsOutput, error) {
	if len(definitions) == 0 {
		return ModelsOutput{}, fmt.Errorf("modelgen: at least one model is required")
	}
	facts, err := GenerateFactsDTOs(definitions, FactsOptions{})
	if err != nil {
		return ModelsOutput{}, err
	}
	models := append([]model.ModelDefinition(nil), definitions...)
	sort.Slice(models, func(i, j int) bool { return models[i].Version < models[j].Version })
	result := ModelsOutput{Artifacts: append([]Artifact{}, facts.Artifacts...)}
	byVersion := map[string]FactsVersion{}
	for _, f := range facts.Versions {
		byVersion[f.Version] = f
	}
	var catalog bytes.Buffer
	fmt.Fprint(&catalog, "// Code generated by Credit Engine modelgen. DO NOT EDIT.\npackage modelbindings\nimport (\"github.com/Zoom7122/alfa-hack-2026-Credit-cabinet/credit-engine/contracts\"\n")
	if len(facts.Versions) > 0 {
		fmt.Fprint(&catalog, "\"io\"\n")
	}
	fmt.Fprintln(&catalog, ")")
	fmt.Fprintln(&catalog, "func generatedRegistrations()[]Registration {return []Registration{")
	paths := map[string]bool{}
	for _, d := range models {
		canonical, err := model.Marshal(d)
		if err != nil {
			return ModelsOutput{}, err
		}
		definitionSHA := fmt.Sprintf("%x", sha256.Sum256(canonical))
		versionSHA := fmt.Sprintf("%x", sha256.Sum256([]byte(d.Version)))
		constructor := "definition_" + versionSHA[:16]
		path := "internal/modelbindings/model_" + versionSHA[:16] + "_generated.go"
		if paths[path] {
			return ModelsOutput{}, fmt.Errorf("modelgen: model output path collision")
		}
		paths[path] = true
		var source bytes.Buffer
		fmt.Fprintf(&source, "// Code generated by Credit Engine modelgen. DO NOT EDIT.\n// Model: %s; SHA256: %s.\npackage modelbindings\nimport (%q;%q)\nfunc %s() model.ModelDefinition{return ", d.Version, definitionSHA, modulePath+"/contracts", modulePath+"/internal/model", constructor)
		if err = goValue(&source, reflect.ValueOf(d)); err != nil {
			return ModelsOutput{}, err
		}
		fmt.Fprintln(&source, "}")
		code, err := format.Source(source.Bytes())
		if err != nil {
			return ModelsOutput{}, fmt.Errorf("modelgen: format model %s: %w", d.Version, err)
		}
		result.Artifacts = append(result.Artifacts, Artifact{Path: path, Data: code})
		info, usesFacts := byVersion[d.Version]
		schemaSHA := ""
		if usesFacts {
			fields := []model.Parameter{}
			for _, p := range d.Parameters {
				if p.Enabled && p.Source.Kind == model.Supplier {
					fields = append(fields, p)
				}
			}
			schemaSHA, err = model.FactsSchemaSHA256(fields)
			if err != nil {
				return ModelsOutput{}, err
			}
		}
		fmt.Fprintf(&catalog, "{Metadata:Metadata{ID:%q,Version:%q,BorrowerType:contracts.BorrowerType(%q),FactsSchemaVersion:%q,DefinitionSHA256:%q,FactsSchemaSHA256:%q,UsesFacts:%t,FormatVersion:%d},Definition:%s", d.ID, d.Version, d.BorrowerType, d.FactsSchemaVersion, definitionSHA, schemaSHA, usesFacts, d.FormatVersion, constructor)
		if usesFacts {
			fmt.Fprintf(&catalog, ",DecodeFacts:func(reader io.Reader,expected contracts.ScoringFactsExpectation)(Facts,error){response,err:=contracts.%s(reader,expected);if err!=nil{return Facts{},err};return Facts{Metadata:response.ScoringFactsMetadata,Values:%s(response.AdditionalFacts)},nil}", info.DecodeFunction, info.AccessorFunction)
		}
		fmt.Fprintln(&catalog, "},")
	}
	fmt.Fprintln(&catalog, "}}\nfunc NewDefault()(*Catalog,error){return New(generatedRegistrations())}")
	code, err := format.Source(catalog.Bytes())
	if err != nil {
		return ModelsOutput{}, fmt.Errorf("modelgen: format model catalog: %w", err)
	}
	result.Artifacts = append(result.Artifacts, Artifact{Path: "internal/modelbindings/catalog_generated.go", Data: code})
	sort.Slice(result.Artifacts, func(i, j int) bool { return result.Artifacts[i].Path < result.Artifacts[j].Path })
	return result, nil
}

func typeName(t reflect.Type) (string, error) {
	if t == reflect.TypeOf(model.NumberLiteral("")) {
		return "model.NumberLiteral", nil
	}
	if t.Kind() == reflect.Slice {
		element, err := typeName(t.Elem())
		return "[]" + element, err
	}
	if t.PkgPath() == "" {
		return t.Name(), nil
	}
	if t.PkgPath() == modulePath+"/internal/model" {
		return "model." + t.Name(), nil
	}
	if t.PkgPath() == modulePath+"/contracts" {
		return "contracts." + t.Name(), nil
	}
	return "", fmt.Errorf("modelgen: unsupported definition type %s", t)
}
func goValue(out *bytes.Buffer, v reflect.Value) error {
	if v.Kind() == reflect.Pointer {
		if v.IsNil() {
			fmt.Fprint(out, "nil")
			return nil
		}
		if v.Elem().Kind() == reflect.Struct {
			fmt.Fprint(out, "&")
			return goValue(out, v.Elem())
		}
		fmt.Fprint(out, "modelPointer(")
		if err := goValue(out, v.Elem()); err != nil {
			return err
		}
		fmt.Fprint(out, ")")
		return nil
	}
	name, err := typeName(v.Type())
	if err != nil {
		return err
	}
	switch v.Kind() {
	case reflect.Struct:
		fmt.Fprint(out, name, "{")
		for i := 0; i < v.NumField(); i++ {
			field := v.Field(i)
			zero := field.IsZero()
			if field.Kind() == reflect.Float64 && field.Float() == 0 && math.Signbit(field.Float()) {
				zero = false
			}
			if zero {
				continue
			}
			fmt.Fprint(out, v.Type().Field(i).Name, ":")
			if err = goValue(out, field); err != nil {
				return err
			}
			fmt.Fprint(out, ",")
		}
		fmt.Fprint(out, "}")
	case reflect.Slice:
		if v.IsNil() {
			fmt.Fprint(out, "nil")
			return nil
		}
		fmt.Fprint(out, name, "{")
		for i := 0; i < v.Len(); i++ {
			if err = goValue(out, v.Index(i)); err != nil {
				return err
			}
			fmt.Fprint(out, ",")
		}
		fmt.Fprint(out, "}")
	case reflect.String:
		if v.Type().PkgPath() != "" {
			fmt.Fprint(out, name, "(")
		}
		fmt.Fprint(out, strconv.Quote(v.String()))
		if v.Type().PkgPath() != "" {
			fmt.Fprint(out, ")")
		}
	case reflect.Bool:
		fmt.Fprint(out, strconv.FormatBool(v.Bool()))
	case reflect.Int, reflect.Int64:
		fmt.Fprint(out, strconv.FormatInt(v.Int(), 10))
	case reflect.Float64:
		if v.Float() == 0 && math.Signbit(v.Float()) {
			fmt.Fprint(out, "modelFloat64(0x8000000000000000)")
		} else {
			fmt.Fprint(out, strconv.FormatFloat(v.Float(), 'g', -1, 64))
		}
	default:
		return fmt.Errorf("modelgen: unsupported definition value %s", v.Kind())
	}
	return nil
}

// DefinitionSHA256 identifies canonical model content, including number tokens
// and array order. It never hashes a file's platform-specific line endings.
func DefinitionSHA256(d model.ModelDefinition) (string, error) {
	data, err := model.Marshal(d)
	if err != nil {
		return "", err
	}
	return strings.ToLower(fmt.Sprintf("%x", sha256.Sum256(data))), nil
}
